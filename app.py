def to_blocks(d, k):
    """১ ঘণ্টার candle থেকে প্রতিদিনের হিসেবে k টি করে মিলিয়ে ২/৪ ঘণ্টার candle বানায়
    (NSE: ৪ঘণ্টা = 9:15–13:15 ও 13:15–15:30)।"""
    d = d.assign(_day=d.index.date, _t=d.index)
    d["_g"] = d.groupby("_day").cumcount() // k
    g = d.groupby(["_day", "_g"], sort=True)
    out = pd.DataFrame({"Open": g["Open"].first(), "High": g["High"].max(), "Low": g["Low"].min(),
                        "Close": g["Close"].last(), "Volume": g["Volume"].sum()})
    out.index = pd.DatetimeIndex(g["_t"].first())
    return out


def _lower(c):
    s = pd.Series(c)
    return (s.rolling(20).mean() - 2 * s.rolling(20).std(ddof=0)).values   # Bollinger (20, 2)


def _sig(i, o, h, l, c, v, lo, cond, volx, pmin, pmax):
    """i নম্বর candle-এ কন্ডিশন মিললে (pattern, volume_ratio) ফেরত দেয়।"""
    if np.isnan(lo[i]):
        return None
    avg = v[i - 20:i].mean()
    if cond == "A":
        # কন্ডিশন ১: Green candle, Lower BB তার body-র মাঝামাঝি, সাথে গড়ের চেয়ে বেশি volume
        if c[i] <= o[i]:
            return None
        pos = (lo[i] - o[i]) / (c[i] - o[i])          # 0 = body-র নিচ, 1 = body-র মাথা
        if pmin <= pos <= pmax and avg > 0 and v[i] / avg >= volx:
            return "Green candle @ Lower BB", v[i] / avg
        return None
    # কন্ডিশন ২: Lower BB-র নিচে Hammer / Morning Star – reversal candle band ছোঁবে না (high < lower)
    vr = v[i] / avg if avg > 0 else np.nan
    rng, body = h[i] - l[i], abs(c[i] - o[i])
    low_w, up_w = min(o[i], c[i]) - l[i], h[i] - max(o[i], c[i])
    if rng > 0 and low_w >= 2 * body and low_w >= 0.6 * rng and up_w <= max(0.5 * body, 0.1 * rng) \
            and h[i] < lo[i]:
        return "Hammer", vr
    a, s = i - 2, i - 1       # Morning Star: বড় লাল → ছোট star (band-এর নিচে, ছোঁয়নি) → সবুজ
    if (c[a] < o[a] and h[s] < lo[s] and abs(c[s] - o[s]) < 0.5 * abs(c[a] - o[a])
            and (o[s] + c[s]) / 2 <= c[a] and c[i] > o[i] and c[i] > (o[a] + c[a]) / 2):
        return "Morning Star", vr
    return None


def fmt_time(t, tf):
    if tf in INTRADAY:
        return t.strftime("%d %b, %H:%M")
    return t.strftime("%b %Y") if tf == "Monthly" else t.strftime("%d %b %Y")


def scan(data, cond, tf, k=3, volx=1.5, pmin=0.25, pmax=0.75, names=None):
    """data: {symbol: DataFrame(Open,High,Low,Close,Volume)}; শেষ k টি candle-এ সিগন্যাল খোঁজে।"""
    names = names or {}
    intr = tf in INTRADAY
    rows = []
    for sym, d in data.items():
        o, h, l, c, v = (d[x].values.astype(float) for x in ("Open", "High", "Low", "Close", "Volume"))
        n = len(c)
        if n < 30:
            continue
        lo, idx = _lower(c), d.index
        for i in range(n - 1, max(n - k, 22) - 1, -1):
            r = _sig(i, o, h, l, c, v, lo, cond, volx, pmin, pmax)
            if not r:
                continue
            if intr:   # আগের দিনের close-এর তুলনায়
                days = np.array([t.date() for t in idx])
                prev = c[days < days[-1]]
                chg = (c[-1] / prev[-1] - 1) * 100 if len(prev) else np.nan
            else:      # আগের candle-এর close-এর তুলনায়
                chg = (c[-1] / c[-2] - 1) * 100
            rows.append({
                "Stock": sym, "Company": names.get(sym, ""), "Signal Time": fmt_time(idx[i], tf),
                "Ago": n - 1 - i, "Signal Price": c[i], "LTP": c[-1], "Change %": chg,
                "Lower BB": lo[i], "Pattern": r[0], "Volume ×": r[1],
                "Chart": "https://in.tradingview.com/chart/?symbol=NSE%3A" + quote(sym.replace("-", "_"), safe="")
                         + "&interval=" + TF[tf][4],
            })
            break
    df = pd.DataFrame(rows)
    if not df.empty:
        df = df.sort_values(["Ago", "Volume ×"], ascending=[True, False]).reset_index(drop=True)
    return df



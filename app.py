@st.cache_data(show_spinner=False, max_entries=200)
def load_batch(batch: tuple, tf: str, bucket: int):
    """bucket বদলালে (cache সময় পেরোলে) নতুন করে ডেটা আনে।"""
    interval, period, k = TF[tf][:3]
    tk = [s + ".NS" for s in batch]
    df = None
    for _ in range(2):
        try:
            df = yf.download(tk, period=period, interval=interval, group_by="ticker",
                             threads=True, progress=False, auto_adjust=False)
            if df is not None and len(df):
                break
        except Exception:
            time.sleep(1.5)
    out = {}
    if df is None or df.empty:
        return out
    multi = isinstance(df.columns, pd.MultiIndex)
    for s, t in zip(batch, tk):
        try:
            d = (df[t] if multi else df).dropna(subset=["Close"])
            if k:
                d = to_blocks(d, k)
            d = d[["Open", "High", "Low", "Close", "Volume"]].tail(120)
            if len(d) >= 30:
                out[s] = d
        except Exception:
            pass          # Yahoo-তে ticker না থাকলে বাদ
    return out


def load_all(symbols, tf):
    bucket = int(time.time() // TF[tf][3])
    data, B = {}, 100
    bar = st.progress(0.0, text="ডেটা আনা হচ্ছে…")
    for i in range(0, len(symbols), B):
        data.update(load_batch(tuple(symbols[i:i + B]), tf, bucket))
        bar.progress(min(1.0, (i + B) / len(symbols)),
                     text=f"ডেটা আনা হচ্ছে… {min(i + B, len(symbols))}/{len(symbols)} স্টক")
    bar.empty()
    return data


